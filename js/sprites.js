// Helper : dessine un sprite défini en chaînes de caractères (pixel art).
// Chaque caractère du sprite correspond à une couleur dans PALETTE.
// "." (point) = transparent.
function drawSprite(ctx, spriteData, x, y, scale = 1) {
  const lines = spriteData.trim().split('\n');
  for (let py = 0; py < lines.length; py++) {
    const line = lines[py];
    for (let px = 0; px < line.length; px++) {
      const color = PALETTE[line[px]];
      if (color) {
        ctx.fillStyle = color;
        ctx.fillRect(x + px * scale, y + py * scale, scale, scale);
      }
    }
  }
}

// Variante qui remplace certains caractères du sprite par d'autres entrées
// de la palette (utile pour décliner le même sprite avec des couleurs différentes,
// comme les PNJ qui réutilisent le sprite du joueur).
function drawSpriteRecolored(ctx, spriteData, x, y, scale = 1, colorMap = {}) {
  const lines = spriteData.trim().split('\n');
  for (let py = 0; py < lines.length; py++) {
    const line = lines[py];
    for (let px = 0; px < line.length; px++) {
      const ch = line[px];
      const mapped = colorMap[ch] !== undefined ? colorMap[ch] : ch;
      const color = PALETTE[mapped];
      if (color) {
        ctx.fillStyle = color;
        ctx.fillRect(x + px * scale, y + py * scale, scale, scale);
      }
    }
  }
}

// Cercle "pixelisé" — utile pour les créatures et effets
function pxCircle(ctx, cx, cy, r, color) {
  ctx.fillStyle = color;
  const r2 = r * r;
  for (let y = -r; y <= r; y++) {
    for (let x = -r; x <= r; x++) {
      if (x * x + y * y <= r2) {
        ctx.fillRect(cx + x, cy + y, 1, 1);
      }
    }
  }
}

function pxRing(ctx, cx, cy, rOut, rIn, color) {
  ctx.fillStyle = color;
  const rO2 = rOut * rOut, rI2 = rIn * rIn;
  for (let y = -rOut; y <= rOut; y++) {
    for (let x = -rOut; x <= rOut; x++) {
      const d = x * x + y * y;
      if (d <= rO2 && d > rI2) {
        ctx.fillRect(cx + x, cy + y, 1, 1);
      }
    }
  }
}

